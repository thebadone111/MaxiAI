"""
Trace public/maxi-icon.png (the serif M crossed by two signal-red rules)
into public/maxi-mark.svg.

This is a reconstruction, not the original artwork: no vector of the mark
exists, so the 1024px PNG is upscaled, thresholded at the anti-aliasing
midpoint (which puts the edge at sub-pixel accuracy) and its contours are
simplified to polygons. At the sizes the site draws the mark -- 28px in the
header to ~220px in the intro -- the polygon is indistinguishable from curves.

The SVG keeps the letter and the rules as separate paths:
  id="m"      the letter, ink           (src/intro mark-targets samples this)
  id="rules"  both rules, signal red

It also writes src/elems/mark-paths.js (the same paths, for the inline <Mark>
component and the intro's point sampler).

    python tools/brand/trace_mark.py
"""
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "public" / "maxi-icon.png"
OUT = ROOT / "public" / "maxi-mark.svg"
JS = ROOT / "src" / "elems" / "mark-paths.js"
UP = 2           # supersample factor
EPS = 1.4        # polygon tolerance, in supersampled px


def mask_for(img, which):
    b, g, r = [img[..., i].astype(np.int16) for i in range(3)]
    if which == "ink":
        # Dark and not red: the letter. The paper is ~(225,220,210).
        lum = (r + g + b) / 3
        m = np.clip((150 - lum) * 255 / 100, 0, 255)
        m[(r - b) > 60] = 0
    else:
        # Red: strong r over g/b.
        m = np.clip(((r - (g + b) / 2) - 40) * 255 / 80, 0, 255)
    return m.astype(np.uint8)


def contours_of(mask, min_area):
    big = cv2.resize(mask, None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
    # A light blur before thresholding irons out the paper texture and the
    # JPEG-ish stair-stepping, without rounding the hairline serifs away.
    big = cv2.GaussianBlur(big, (0, 0), 1.6)
    _, bw = cv2.threshold(big, 127, 255, cv2.THRESH_BINARY)
    cs, hier = cv2.findContours(bw, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    out = []
    for c in cs:
        if cv2.contourArea(c) < min_area * UP * UP:
            continue
        p = cv2.approxPolyDP(c, EPS, True).reshape(-1, 2) / UP
        out.append(p)
    return out


def d_of(polys, ox, oy):
    parts = []
    for p in polys:
        pts = [f"{x - ox:.1f} {y - oy:.1f}" for x, y in p]
        parts.append("M" + " L".join(pts) + "Z")
    return "".join(parts)


def main():
    img = cv2.imread(str(SRC), cv2.IMREAD_COLOR)
    if img is None:
        sys.exit(f"cannot read {SRC}")
    ink_m = mask_for(img, "ink")
    red_m = mask_for(img, "red")
    # The rules are drawn over the letter, so the raster has no ink under
    # them. Bridge the letter through: a vertical closing, applied only where
    # the rules are, so nothing else in the glyph is thickened.
    closed = cv2.morphologyEx(ink_m, cv2.MORPH_CLOSE, np.ones((60, 1), np.uint8))
    under = cv2.dilate(red_m, np.ones((5, 5), np.uint8)) > 60
    ink_m[under] = np.maximum(ink_m[under], closed[under])
    ink = contours_of(ink_m, 400)
    red = contours_of(red_m, 200)
    allp = np.vstack(ink + red)
    pad = 2
    x0, y0 = allp.min(axis=0) - pad
    x1, y1 = allp.max(axis=0) + pad
    w, h = x1 - x0, y1 - y0
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.0f} {h:.0f}">\n'
        "<!-- Reconstruction traced from maxi-icon.png by tools/brand/trace_mark.py. "
        "Replace with the original vector if one ever exists. -->\n"
        f'<path id="m" fill="#1C1A2E" fill-rule="evenodd" d="{d_of(ink, x0, y0)}"/>\n'
        f'<path id="rules" fill="#C0392B" d="{d_of(red, x0, y0)}"/>\n'
        "</svg>\n"
    )
    OUT.write_text(svg, encoding="utf-8")
    JS.write_text(
        "// Generated by tools/brand/trace_mark.py from public/maxi-icon.png. Do not edit.\n"
        "export const MARK = {\n"
        f"  viewBox: '0 0 {w:.0f} {h:.0f}',\n"
        f"  width: {w:.0f},\n  height: {h:.0f},\n"
        f"  m: '{d_of(ink, x0, y0)}',\n"
        f"  rules: '{d_of(red, x0, y0)}',\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"{OUT.name}: viewBox {w:.0f}x{h:.0f}, ink {len(ink)} paths "
          f"({sum(len(p) for p in ink)} pts), red {len(red)} paths, {len(svg)} bytes")


if __name__ == "__main__":
    main()
